//go:build !windows

// Package testjob — заглушка для платформ без Job Object.
//
// Механизм нужен только на Windows: там os/exec ждёт закрытия унаследованного
// пайпа, и осиротевший потомок держит шаг CI до бесконечного таймаута. На
// linux/macOS такой проблемы нет, поэтому здесь всё no-op.
//
// Заглушка существует, чтобы тестовые файлы с TestMain не нужно было прятать
// под //go:build windows: иначе в пакете не осталось бы TestMain на других
// платформах и CI-шаги разъедутся по платформам.
package testjob

// Adopt — no-op вне Windows: job'а здесь нет, делать нечего, ломать нечего.
// Возвращает nil, чтобы вызывающий TestMain работал одинаково на всех
// платформах и не нуждался в собственных проверках.
func Adopt() error { return nil }

// KeepAlive — no-op вне Windows. На Windows здесь удерживается handle job'а.
func KeepAlive() {}
